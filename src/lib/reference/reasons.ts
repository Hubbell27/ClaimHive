/**
 * Reason codes dental offices see on EOBs and 835 remittances, in ClaimHive's
 * own plain-English words (not the official X12 text):
 *   - group codes (who owes the adjusted amount),
 *   - CARC: Claim Adjustment Reason Codes (why a line was adjusted or denied),
 *   - RARC: Remittance Advice Remark Codes (extra detail, often "what's missing").
 * The official lists are maintained by X12 (x12.org/codes). A code that isn't
 * here is shown as "not in ClaimHive's list" with a link to them.
 */
export type ReasonKind = "group" | "carc" | "rarc";
export type ReasonCategory =
  | "patient" | "contractual" | "missing_info" | "documentation" | "coverage" | "frequency" | "bundling" | "coding"
  | "authorization" | "timely_filing" | "duplicate" | "cob" | "necessity" | "provider" | "info";

export interface ReasonCode { kind: ReasonKind; code: string; label: string; category: ReasonCategory; action?: string }

