const KEY = (kind: ReasonKind, code: string) => `${kind}:${code.toUpperCase()}`;
const BY_KEY = new Map(REASON_CODES.map((x) => [KEY(x.kind, x.code), x]));

export function findReason(kind: ReasonKind, code: string): ReasonCode | undefined {
  return BY_KEY.get(KEY(kind, code));
}
export const actionFor = (x: ReasonCode) => x.action ?? CATEGORY[x.category].action;
export const anchorFor = (kind: ReasonKind, code: string) => `${kind}-${code.toUpperCase()}`;
/** Where a code is explained: the lookup page, filtered to it. */
export const codeHref = (kind: ReasonKind, code: string) => `/app/codes?q=${encodeURIComponent(code)}#${anchorFor(kind, code)}`;

/** Search by code (exact or prefix, with or without group, e.g. "CO-16") or by words in the text. */
export function searchReasons(q: string): ReasonCode[] {
  const s = q.trim().toUpperCase().replace(/^(CO|PR|OA|PI)[\s-]+(?=\w)/, "");
  if (!s) return REASON_CODES;
  const exact = REASON_CODES.filter((x) => x.code.toUpperCase() === s);
  const prefix = REASON_CODES.filter((x) => x.code.toUpperCase().startsWith(s) && !exact.includes(x));
  const words = s.toLowerCase().split(/\s+/).filter(Boolean);
  const norm = (t: string) => t.toLowerCase().replace(/-/g, "");
  const has = (t: string) => words.every((w) => norm(t).includes(norm(w)));
  const rest = REASON_CODES.filter((x) => !exact.includes(x) && !prefix.includes(x));
  // Codes whose name matches come first, then ones that only match in the advice.
  const named = rest.filter((x) => has(`${x.label} ${CATEGORY[x.category].name}`));
  const mentioned = rest.filter((x) => !named.includes(x) && has(`${x.label} ${CATEGORY[x.category].name} ${actionFor(x)}`));
  return [...exact, ...prefix, ...named, ...mentioned];
}
